"""Emit glerr.c: a DYLD_INSERT_LIBRARIES wrapper that names the GL call raising a GL error.

Usage: emit_glerr.py <sdk path> <out .c>
It preprocesses the OpenGL framework's gl.h and glext.h (so only the prototypes the SDK really
declares remain), parses the `extern <ret> <name> (<params>);` prototypes and wraps each one: after the call it drains glGetError and logs
`glerr: <name> -> 0x<code>` to stderr. glGetError, glBegin and glEnd are written by hand
(no GL call may check for errors between glBegin and glEnd).
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

INCLUDES = "#include <OpenGL/gl.h>\n#include <OpenGL/glext.h>\n"
HAND_WRITTEN = {"glGetError", "glBegin", "glEnd"}
PROTO = re.compile(
    r"^extern\s+(?P<ret>[\w\s\*]+?)\s*\b(?P<name>gl\w+)\s*\((?P<params>[^()]*)\)"
    r"\s*$"
)
PARAM = re.compile(r"^(?P<type>.*?)(?P<name>\b\w+)?\s*(?P<arr>\[[^\]]*\])?$", re.S)
C_TYPE_WORDS = {"void", "int", "char", "short", "long", "float", "double", "unsigned", "signed", "const"}

PROLOGUE = r'''/* Generated by tools/glcount/emit_glerr.py; do not edit. */
#define GL_SILENCE_DEPRECATION
#define GL_GLEXT_PROTOTYPES
#include <OpenGL/gl.h>
#include <OpenGL/glext.h>
#include <stdatomic.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define DYLD_INTERPOSE(repl, orig)                                                   \
    __attribute__((used)) static struct {                                            \
        const void *replacement;                                                     \
        const void *replacee;                                                        \
    } interpose_##orig __attribute__((section("__DATA,__interpose"))) = {             \
        (const void *)(unsigned long)&repl, (const void *)(unsigned long)&orig}

#define GLERR_TABLE 256

typedef struct {
    const char *name;
    GLenum code;
    unsigned long count;
} glerr_entry;

static glerr_entry g_table[GLERR_TABLE];
static int g_entries;
static unsigned long g_overflow; /* errors counted after the table filled */
static unsigned long g_get_error_calls;
static unsigned long g_max_print = 20;
static atomic_flag g_lock = ATOMIC_FLAG_INIT;
static _Thread_local int t_begin_depth;

static void glerr_totals(void);

/* Children must not inherit the insert: the x86_64 Cg helper cannot load an
 * arm64 dylib, so dyld kills it and every Cg call then returns 0. */
__attribute__((constructor)) static void glerr_init(void)
{
    unsetenv("DYLD_INSERT_LIBRARIES");
    const char *m = getenv("GLERR_MAX");
    if (m != NULL)
        g_max_print = strtoul(m, NULL, 10);
    atexit(glerr_totals);
    fprintf(stderr, "glerr: wrapping %d functions\n", GLERR_NFUNCS);
}

static void glerr_lock(void)
{
    while (atomic_flag_test_and_set_explicit(&g_lock, memory_order_acquire)) {
    }
}
static void glerr_unlock(void) { atomic_flag_clear_explicit(&g_lock, memory_order_release); }

static void glerr_check(const char *name)
{
    if (t_begin_depth > 0)
        return;
    for (int i = 0; i < 8; i++) {
        GLenum e = glGetError(); /* the real one: the interpose does not apply inside this dylib */
        if (e == GL_NO_ERROR)
            return;
        unsigned long n = 0;
        glerr_lock();
        int k = 0;
        while (k < g_entries && !(g_table[k].name == name && g_table[k].code == e))
            k++;
        if (k == g_entries && g_entries < GLERR_TABLE) {
            g_table[k].name = name;
            g_table[k].code = e;
            g_entries++;
        }
        if (k < g_entries)
            n = ++g_table[k].count;
        else
            g_overflow++;
        glerr_unlock();
        if (n != 0 && n <= g_max_print)
            fprintf(stderr, "glerr: %s -> 0x%04X\n", name, e);
    }
}

static int glerr_cmp(const void *a, const void *b)
{
    const glerr_entry *x = a, *y = b;
    return (y->count > x->count) - (y->count < x->count);
}

static void glerr_totals(void)
{
    glerr_lock();
    qsort(g_table, (size_t)g_entries, sizeof g_table[0], glerr_cmp);
    fprintf(stderr, "glerr: totals (glGetError calls %lu, errors not tabled %lu)\n", g_get_error_calls,
            g_overflow);
    for (int i = 0; i < g_entries && i < 30; i++)
        fprintf(stderr, "glerr:   %-40s 0x%04X %10lu\n", g_table[i].name, g_table[i].code, g_table[i].count);
    glerr_unlock();
}

static GLenum glerr_glGetError(void)
{
    __atomic_fetch_add(&g_get_error_calls, 1, __ATOMIC_RELAXED);
    return glGetError();
}
DYLD_INTERPOSE(glerr_glGetError, glGetError);

static void glerr_glBegin(GLenum mode)
{
    t_begin_depth++;
    glBegin(mode);
}
DYLD_INTERPOSE(glerr_glBegin, glBegin);

static void glerr_glEnd(void)
{
    glEnd();
    if (t_begin_depth > 0)
        t_begin_depth--;
    glerr_check("glEnd");
}
DYLD_INTERPOSE(glerr_glEnd, glEnd);

'''


def preprocess(sdk: Path) -> str:
    """The two headers after the preprocessor, as the compiler sees them."""
    cmd = ["clang", "-E", "-P", "-x", "c", "-arch", "arm64", "-isysroot", str(sdk),
           "-DGL_SILENCE_DEPRECATION", "-DGL_GLEXT_PROTOTYPES", "-"]
    return subprocess.run(cmd, input=INCLUDES, capture_output=True, text=True, check=True).stdout


def statements(text: str):
    """Yield each `extern ...;` declaration with line breaks flattened."""
    for m in re.finditer(r"(?m)^[ \t]*extern\b[^;]*;", text):
        yield " ".join(m.group(0).split())


def parse(stmt: str):
    """Return (ret, name, [decls], [arg names]) or None when the prototype is not understood."""
    m = PROTO.match(stmt.rstrip(";").strip())
    if m is None:
        return None
    raw = m.group("params").strip()
    decls: list[str] = []
    args: list[str] = []
    if raw not in ("", "void"):
        for i, p in enumerate(raw.split(",")):
            p = p.strip()
            pm = PARAM.match(p)
            if pm is None or not p:
                return None
            ptype, pname = pm.group("type").strip(), pm.group("name")
            # A trailing word is a type (unnamed parameter) when it starts with GL or is a C type word.
            if pname is not None and (pname.startswith("GL") or pname in C_TYPE_WORDS):
                ptype, pname = (ptype + " " + pname).strip(), None
            if pm.group("arr"):
                ptype += " *"
            decls.append(f"{ptype} p{i}")
            args.append(f"p{i}")
    return m.group("ret").strip(), m.group("name"), decls, args


def emit(sdk: Path) -> tuple[str, int, int]:
    funcs: dict[str, tuple[str, list[str], list[str]]] = {}
    skipped = 0
    for stmt in statements(preprocess(sdk)):
        mname = re.search(r"\b(gl\w+)\s*\(", stmt)
        if mname is None or mname.group(1) in HAND_WRITTEN:
            continue
        parsed = parse(stmt)
        if parsed is None:
            skipped += 1
            continue
        ret, name, decls, args = parsed
        funcs.setdefault(name, (ret, decls, args))
    out = [f"#define GLERR_NFUNCS {len(funcs) + 3}\n", PROLOGUE]
    for name, (ret, decls, args) in sorted(funcs.items()):
        decl = ", ".join(decls) if decls else "void"
        call = f"{name}({', '.join(args)})"
        if ret == "void":
            body = f'{call}; glerr_check("{name}");'
        else:
            body = f'{ret} r = {call}; glerr_check("{name}"); return r;'
        out.append(f"static {ret} glerr_{name}({decl}) {{ {body} }}\nDYLD_INTERPOSE(glerr_{name}, {name});\n")
    return "".join(out), len(funcs), skipped


def main() -> None:
    sdk, dest = Path(sys.argv[1]), Path(sys.argv[2])
    code, emitted, skipped = emit(sdk)
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(code)
    print(f"emitted {emitted}, skipped {skipped}", file=sys.stderr)


if __name__ == "__main__":
    main()
