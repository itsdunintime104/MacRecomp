"""Derive per-game build inputs from game.toml, the game binary and feral_frontend.toml.

    python -m tools.game.derive --profile <game.toml> [--out DIR]

Entries named in the profile's `absent` list (and the NuMain CFString) are skipped; feral_symbols.h says which are present
with FE_HAS_<NAME> 1 or 0.

Writes game_config.h, feral_symbols.h, frontend_rename.h, native_overrides.txt, gen_segments.h,
game.mk and derived.json into DIR (default <game root>/build.nosync/game).
"""
from __future__ import annotations

import argparse
import hashlib
import json
import struct
import sys
import tomllib
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from tools.game import feral, profile
from tools.game.feral import FeralError, Frontend, Image, Resolved, Role
from tools.hobbit import emit_runtime

STEAM_COMMON = "/Library/Application Support/Steam/steamapps/common/"
STATIC_ALIGN = 0x10000
STATIC_SIZE = 0x20000
HEAP_BASE = 0x20000000
NUMAIN = b"NuMain\0"
NUMAIN_LENGTH = 6
CFSTRING_SIZE = 16


@dataclass(frozen=True)
class Derived:
    entry: int
    static_base: int
    cfstr_numain: int
    functions: dict[str, Resolved]
    data: dict[str, int]
    absent: frozenset[str]


def static_base(img: Image) -> int:
    base = (img.hi + STATIC_ALIGN - 1) & ~(STATIC_ALIGN - 1)
    if base + STATIC_SIZE > HEAP_BASE:
        raise FeralError(
            f"static area 0x{base:08X}+0x{STATIC_SIZE:X} does not fit below 0x{HEAP_BASE:08X}"
        )
    return base


def find_numain_cfstring(img: Image) -> int:
    cstring = next((s for full, s in img.sections if full.endswith(".__cstring")), None)
    cfstring = next((s for full, s in img.sections if full.endswith(".__cfstring")), None)
    if cstring is None or cfstring is None:
        raise FeralError("no __cstring or __cfstring section")
    blob = img.data[cstring.offset:cstring.offset + cstring.size]
    strings = {
        cstring.addr + i
        for i in range(len(blob))
        if blob.startswith(NUMAIN, i) and (i == 0 or blob[i - 1] == 0)
    }
    found: list[int] = []
    for k in range(cfstring.size // CFSTRING_SIZE):
        _isa, _flags, ptr, length = struct.unpack_from("<IIII", img.data, cfstring.offset + CFSTRING_SIZE * k)
        if ptr in strings and length == NUMAIN_LENGTH:
            found.append(cfstring.addr + CFSTRING_SIZE * k)
    if len(found) != 1:
        raise FeralError(f"NuMain CFString: found {len(found)} entries, expected 1")
    return found[0]


def compute(prof: profile.Profile, fe: Frontend, img: Image) -> Derived:
    absent = frozenset(prof.absent)
    feral.validate_absent(fe, absent)
    has_numain = feral.NUMAIN_ENTRY not in absent
    functions = feral.resolve(img, fe, prof.pins, absent)
    return Derived(
        entry=img.parsed.entry,
        static_base=static_base(img),
        cfstr_numain=find_numain_cfstring(img) if has_numain else 0,
        functions=functions,
        data=feral.derive_data(img, fe, functions, absent),
        absent=absent,
    )


def _header(prof: profile.Profile, guard: str, body: list[str]) -> str:
    lines = [
        f"/* Generated by tools/game/derive.py for {prof.id}. Do not edit. */",
        f"#ifndef {guard}",
        f"#define {guard}",
        "",
        *body,
        "",
        "#endif",
    ]
    return "\n".join(lines) + "\n"


def render_game_config(prof: profile.Profile, derived: Derived) -> str:
    p = prof.env_prefix
    body = [
        f'#define GAME_ID "{prof.id}"',
        f'#define GAME_TITLE "{prof.title}"',
        f'#define GAME_WINDOW_TITLE "{prof.window_title}"',
        f"#define GAME_STEAM_APP_ID {prof.steam_app_id}u",
        f'#define GAME_STEAM_APP_IN_HOME "{STEAM_COMMON}{prof.steam_app}"',
        f'#define GAME_SUPPORT_DIR "{prof.support_dir}"',
        f'#define GAME_ENV_APP "{p}_APP"',
        f'#define GAME_ENV_SAVE_DIR "{p}_SAVE_DIR"',
        f'#define GAME_ENV_CGHELPER "{p}_CGHELPER"',
        f'#define GAME_ENV_CG_CACHE "{p}_CG_CACHE"',
        f"#define GAME_ENTRY_VA 0x{derived.entry:08X}u",
        f"#define GAME_STATIC_BASE 0x{derived.static_base:08X}u",
        f"#define GAME_CFSTR_NUMAIN 0x{derived.cfstr_numain:08X}u",
    ]
    return _header(prof, "GAME_CONFIG_H", body)


def _by_role(fe: Frontend, derived: Derived, *roles: Role) -> list[tuple[str, int]]:
    return [
        (f.name, derived.functions[f.name].va)
        for f in fe.functions
        if f.role in roles and f.name in derived.functions
    ]


def _frontend_sorted(fe: Frontend, derived: Derived) -> list[tuple[str, int]]:
    return sorted(_by_role(fe, derived, Role.FRONTEND), key=lambda item: item[1])


def render_feral_symbols(prof: profile.Profile, fe: Frontend, derived: Derived) -> str:
    body = [f"#define {name} sub_{va:08X}" for name, va in _by_role(fe, derived, Role.FRONTEND, Role.PAD)]
    body.append("")
    body += [
        f"#define {f.name.upper()}_VA 0x{derived.functions[f.name].va:08X}u"
        for f in fe.functions
        if f.name in derived.functions
    ]
    body.append("")
    body += [f"#define {name} 0x{va:08X}u" for name, va in derived.data.items()]
    body.append("")
    body += [
        f"#define FE_HAS_{name.upper()} {0 if name in derived.absent else 1}"
        for name in [*(f.name for f in fe.functions), *(d.name for d in fe.data)]
    ]
    frontend = _frontend_sorted(fe, derived)
    if not frontend:
        raise FeralError("no frontend functions in feral_frontend.toml")
    body += [
        "",
        f"#define FE_REPLACED_LO 0x{frontend[0][1]:08X}u",
        f"#define FE_REPLACED_HI 0x{frontend[-1][1] + 1:08X}u",
        "#define FE_REPLACED_TABLE \\",
    ]
    for i, (name, va) in enumerate(frontend):
        tail = " \\" if i < len(frontend) - 1 else ""
        body.append(f"    {{0x{va:08X}u, {name}}},{tail}")
    return _header(prof, "FERAL_SYMBOLS_H", body)


def render_frontend_rename(prof: profile.Profile, fe: Frontend, derived: Derived) -> str:
    body = [f"#define sub_{va:08X} lifted_sub_{va:08X}" for _name, va in _frontend_sorted(fe, derived)]
    return _header(prof, "FRONTEND_RENAME_H", body)


def render_native_overrides(prof: profile.Profile, fe: Frontend, derived: Derived) -> str:
    lines = [
        "# Guest functions replaced by native code (weak in the generated C, strong in the runtime).",
        f"# Generated by tools/game/derive.py for {prof.id}. Do not edit.",
    ]
    lines += [f"0x{va:08X}" for va in sorted(va for _n, va in _by_role(fe, derived, Role.PAD))]
    return "\n".join(lines) + "\n"


def _make_path(path: Path) -> str:
    return str(path).replace(" ", "\\ ")


def render_game_mk(prof: profile.Profile, fe: Frontend, derived: Derived) -> str:
    regex = "|".join(f"sub_{va:08X}" for _name, va in _frontend_sorted(fe, derived))
    return "\n".join([
        f"# Generated by tools/game/derive.py for {prof.id}. Do not edit.",
        f"GAME_ID := {prof.id}",
        f"GAME_DEPS := {_make_path(prof.binary)} {_make_path(prof.analysis)}",
        f"IMPORT_SIGS := {_make_path(prof.import_sigs)}",
        f"FE_LIFTED_RE := {regex}",
    ]) + "\n"


def render_derived_json(prof: profile.Profile, derived: Derived) -> str:
    doc: dict[str, Any] = {
        "id": prof.id,
        "entry": derived.entry,
        "static_base": derived.static_base,
        "cfstr_numain": derived.cfstr_numain,
        "functions": {
            name: {"va": r.va, "rule": str(r.rule), "matches": r.matches}
            for name, r in derived.functions.items()
        },
        "data": derived.data,
    }
    return json.dumps(doc, indent=2) + "\n"


def render_all(prof: profile.Profile, fe: Frontend, derived: Derived, analysis: dict[str, Any]) -> dict[str, str]:
    return {
        "game_config.h": render_game_config(prof, derived),
        "feral_symbols.h": render_feral_symbols(prof, fe, derived),
        "frontend_rename.h": render_frontend_rename(prof, fe, derived),
        "native_overrides.txt": render_native_overrides(prof, fe, derived),
        "gen_segments.h": emit_runtime.render(analysis),
        "game.mk": render_game_mk(prof, fe, derived),
        "derived.json": render_derived_json(prof, derived),
    }


def write_outputs(files: dict[str, str], out: Path) -> list[Path]:
    """Write each file whose content changed; return the paths written."""
    out.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for name, text in files.items():
        path = out / name
        if path.is_file() and path.read_text() == text:
            continue
        path.write_text(text)
        written.append(path)
    return written


def run(profile_path: Path, out: Path | None) -> list[Path]:
    prof = profile.load(profile_path)
    digest = hashlib.sha256(prof.binary.read_bytes()).hexdigest()
    if digest != prof.binary_sha256:
        raise FeralError(f"{prof.binary} sha256 {digest} != binary_sha256 {prof.binary_sha256}")
    fe = feral.load_file(feral.DEFAULT_TOML)
    img = feral.load_image(prof.binary)
    derived = compute(prof, fe, img)
    analysis: dict[str, Any] = json.loads(prof.analysis.read_text())
    files = render_all(prof, fe, derived, analysis)
    return write_outputs(files, out if out is not None else prof.root / "build.nosync" / "game")


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(prog="derive")
    parser.add_argument("--profile", required=True, type=Path)
    parser.add_argument("--out", type=Path)
    args = parser.parse_args(argv)
    try:
        written = run(args.profile, args.out)
    except (FeralError, ValueError, OSError, tomllib.TOMLDecodeError) as exc:
        print(f"derive: {exc}", file=sys.stderr)
        return 1
    for path in written:
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
