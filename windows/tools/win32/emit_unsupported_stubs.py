"""Generate the fallback stub for every Win32 import.

Usage: python -I tools/win32/emit_unsupported_stubs.py notes/win32_imports.md \
           -o runtime/src/win32_unsupported.c

Each stub reports `UNSUPPORTED <dll>!<symbol>: not implemented` once (through
the engine's diag_unsupported), pops the import's arguments as given by the
inventory's "Args bytes popped" column (a cdecl row pops only the return
address) and returns 0. win32_core.c binds a stub when no slice exports the
import. Do not edit the output by hand; rerun this script.
"""

from __future__ import annotations

import argparse
import re
from dataclasses import dataclass
from pathlib import Path

ROW_RE = re.compile(r"^\|(?P<cells>.*)\|\s*$")


@dataclass(frozen=True)
class Import:
    dll: str
    symbol: str
    ordinal: int  # 0 for an import by name
    pop_bytes: int  # argument bytes the callee pops (0 for cdecl)


def parse_inventory(path: Path) -> list[Import]:
    rows: list[Import] = []
    in_table = False
    for line in path.read_text().splitlines():
        if line.startswith("## Imports"):
            in_table = True
            continue
        if not in_table:
            continue
        m = ROW_RE.match(line)
        if m is None:
            continue
        cells = [c.strip() for c in m.group("cells").split("|")]
        if len(cells) != 7 or cells[0] in ("DLL", "") or cells[0].startswith("---"):
            continue
        dll, symbol, ordinal, args = cells[0], cells[1], cells[2], cells[3]
        # A C identifier, or a decorated stdcall name such as _BinkOpen@8.
        m_sym = re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*(?:@([0-9]+))?", symbol)
        if m_sym is None:
            raise SystemExit(f"symbol is not a C identifier or _Name@N: {symbol!r}")
        if args.startswith("cdecl"):
            pop = 0
        elif args.isdigit() and int(args) % 4 == 0:
            pop = int(args)
        else:
            raise SystemExit(f"{dll}!{symbol}: bad args column {args!r}")
        if m_sym.group(1) is not None and int(m_sym.group(1)) != pop:
            raise SystemExit(f"{dll}!{symbol}: args column {args!r} disagrees with the decoration")
        rows.append(Import(dll, symbol, 0 if ordinal == "-" else int(ordinal), pop))
    if not rows:
        raise SystemExit(f"no import rows in {path}")
    return rows


def c_name(symbol: str) -> str:
    """The symbol as part of a C identifier: _BinkOpen@8 -> _BinkOpen_8."""
    return symbol.replace("@", "_")


def emit(rows: list[Import]) -> str:
    out = [
        "/* GENERATED by tools/win32/emit_unsupported_stubs.py from",
        " * notes/win32_imports.md. Do not edit; rerun the script.",
        " *",
        " * One fallback stub per Win32 import: reports UNSUPPORTED once, pops the",
        " * import's stdcall arguments (cdecl rows: only the return address) and",
        " * returns 0. win32_core.c binds a stub when no slice exports the import. */",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "#include <string.h>",
        "#include <strings.h>",
        "",
        '#include "recomp_types.h"',
        '#include "diag.h"',
        "",
        "recomp_func_t win32_unsupported_stub(const char *dll, const char *name, uint16_t ordinal);",
        "uint16_t win32_inventory_ordinal(const char *dll, const char *name);",
        "const char *win32_inventory_name(const char *dll, uint16_t ordinal);",
        "",
    ]
    for i, r in enumerate(rows):
        out += [
            f"static void stub_{i:03d}_{c_name(r.symbol)}(void) /* pops {r.pop_bytes} */",
            "{",
            f'    diag_unsupported("{r.dll}!{r.symbol}", MEM32(g_esp), "not implemented");',
            "    g_eax = 0;",
            f"    g_esp += 4u + {r.pop_bytes}u;",
            "}",
            "",
        ]
    out += [
        "static const struct {",
        "    const char *dll;",
        "    const char *name;",
        "    uint16_t ordinal; /* 0 for an import by name */",
        "    recomp_func_t fn;",
        "} g_stubs[] = {",
    ]
    for i, r in enumerate(rows):
        out.append(f'    {{"{r.dll}", "{r.symbol}", {r.ordinal}, stub_{i:03d}_{c_name(r.symbol)}}},')
    out += [
        "};",
        "",
        "/* The stub for dll!name, or for dll#ordinal when name is NULL or \"\".",
        " * The DLL compares case-insensitively. NULL when the import is not in",
        " * the inventory. */",
        "recomp_func_t win32_unsupported_stub(const char *dll, const char *name, uint16_t ordinal)",
        "{",
        "    int by_name = name != NULL && name[0] != '\\0';",
        "    for (size_t i = 0; i < sizeof g_stubs / sizeof g_stubs[0]; i++) {",
        "        if (strcasecmp(g_stubs[i].dll, dll) != 0)",
        "            continue;",
        "        if (by_name ? strcmp(g_stubs[i].name, name) == 0",
        "                    : g_stubs[i].ordinal != 0 && g_stubs[i].ordinal == ordinal)",
        "            return g_stubs[i].fn;",
        "    }",
        "    return NULL;",
        "}",
        "",
        "/* The ordinal the game imports dll!name by, or 0 when it imports it by",
        " * name or not at all. */",
        "uint16_t win32_inventory_ordinal(const char *dll, const char *name)",
        "{",
        "    for (size_t i = 0; i < sizeof g_stubs / sizeof g_stubs[0]; i++)",
        "        if (strcasecmp(g_stubs[i].dll, dll) == 0 && strcmp(g_stubs[i].name, name) == 0)",
        "            return g_stubs[i].ordinal;",
        "    return 0;",
        "}",
        "",
        "/* The name of the import the game takes from dll by ordinal, or NULL. */",
        "const char *win32_inventory_name(const char *dll, uint16_t ordinal)",
        "{",
        "    for (size_t i = 0; i < sizeof g_stubs / sizeof g_stubs[0]; i++)",
        "        if (g_stubs[i].ordinal != 0 && g_stubs[i].ordinal == ordinal &&",
        "            strcasecmp(g_stubs[i].dll, dll) == 0)",
        "            return g_stubs[i].name;",
        "    return NULL;",
        "}",
    ]
    return "\n".join(out) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("inventory", type=Path)
    ap.add_argument("-o", "--output", type=Path, required=True)
    args = ap.parse_args()
    rows = parse_inventory(args.inventory)
    args.output.write_text(emit(rows))
    print(f"{len(rows)} stubs -> {args.output}")


if __name__ == "__main__":
    main()
