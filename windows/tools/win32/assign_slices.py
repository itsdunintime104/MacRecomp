"""Assign every Win32 import to exactly one thunk slice.

Usage: python -I tools/win32/assign_slices.py notes/win32_imports.md -o notes/slice_owners.md

Slices are by DLL first; KERNEL32 is split by what the function touches. Each
import lands in exactly one slice, so parallel slices never write the same thunk.
"""

from __future__ import annotations

import argparse
import re
from collections import Counter
from pathlib import Path

BY_DLL = {
    "advapi32.dll": "fs", "shell32.dll": "fs", "comdlg32.dll": "fs",
    "user32.dll": "ui", "gdi32.dll": "ui",
    "xinput1_3.dll": "input", "dinput8.dll": "input",
    "x3daudio1_6.dll": "audio",
    "ws2_32.dll": "net",
    "ole32.dll": "com", "oleaut32.dll": "com",
    "d3d9.dll": "d3d", "d3dx9_41.dll": "d3d",
}

CORE = {"CloseHandle", "GetLastError", "SetLastError", "GetProcAddress",
        "GetModuleHandleA", "GetModuleHandleW", "LoadLibraryA", "LoadLibraryW",
        "FreeLibrary", "RaiseException", "RtlUnwind"}

SYNC_RE = re.compile(
    r"Thread|Sleep|Event|Mutex|Semaphore|WaitFor|CriticalSection|Interlocked|"
    r"^Tls|^Fls|PerformanceCounter|PerformanceFrequency|TickCount|SystemTime|"
    r"LocalTime|TimeZone|Affinity|DuplicateHandle|SwitchToThread|"
    r"CompareFileTime|FileTimeTo")

FS_RE = re.compile(
    r"File|Find|Directory|Drive|Disk|StdHandle|Console|PathName|FullPathName|"
    r"TempPath|SetHandleCount|GetFileType|FlushFileBuffers|SetEndOfFile|"
    r"VolumeInformation")


def slice_of(dll: str, name: str) -> str:
    d = dll.lower()
    if d in BY_DLL:
        return BY_DLL[d]
    if name in CORE:
        return "core"
    if SYNC_RE.search(name):
        return "sync"
    if FS_RE.search(name):
        return "fs"
    return "mem"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("inventory", type=Path)
    ap.add_argument("-o", "--output", type=Path, required=True)
    args = ap.parse_args()
    rows = []
    for line in args.inventory.read_text().splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) != 7 or not cells[0].lower().endswith(".dll"):
            continue
        dll, sym, ordinal, nbytes, bucket, plan, iat = cells
        rows.append((slice_of(dll, sym), dll, sym, ordinal, nbytes, bucket, iat))
    rows.sort()
    counts = Counter(r[0] for r in rows)
    out = ["# Thunk slice owners", "",
           "Generated by `tools/win32/assign_slices.py` from `notes/win32_imports.md`.",
           "Every import has exactly one owning slice. A slice implements only its own rows.", "",
           "| Slice | Imports |", "|---|---|"]
    out += [f"| {s} | {n} |" for s, n in sorted(counts.items())]
    out += [f"| total | {len(rows)} |", "",
            "| Slice | DLL | Symbol | Ordinal | Args bytes | Bucket | IAT VA |",
            "|---|---|---|---|---|---|---|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    args.output.write_text("\n".join(out) + "\n")
    print(dict(sorted(counts.items())), "total", len(rows))


if __name__ == "__main__":
    main()
